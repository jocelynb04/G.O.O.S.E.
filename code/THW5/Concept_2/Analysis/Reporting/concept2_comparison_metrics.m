function rows=concept2_comparison_metrics(result,J)
%CONCEPT2_COMPARISON_METRICS Common units and honest trial/closed-design labels.
% Crew are in this model's payload, unlike many published OEW definitions.
% No DOC/noise/emissions or achievable range is invented from a sizing trial.
    rows=struct([]);
    if ~isfield(result.assessment,'last_assessment'), return; end
    a=result.assessment.last_assessment; r=a.ratings;
    [o,~,cfg]=build_concept2_study(result.assumptions,result.engine_id);
    o.geom.W_TO=result.W_TO; o.geom.S_ref=r.S_ref;
    tank=o.geom.wing_fuel_volume()*o.wts.rho_fuel;
    for k=1:numel(a.mission.cases)
        c=a.mission.cases(k);
        burn=NaN; fuel=NaN; block=NaN; perSeat=NaN;
        if c.completed
            burn=c.fuel_burn_lb/c.legs;
            fuel=c.max_leg_fuel_lb*(1+J.missions.std_mission.reserve_fuel_fraction) / ...
                (1-J.missions.std_mission.fuel_accounting.unusable_fuel_fraction_of_total_capacity);
            block=c.elapsed_min/c.legs;
            if ~c.reserve_case, perSeat=burn/(9*c.route_distance_nm); end
        end
        row=struct('case_name',c.name,'engine',result.engine_id, ...
            'mass_closed',result.mass_closed,'mission_feasible',c.feasible, ...
            'completed',c.completed,'evaluated_weight_lb',result.W_TO, ...
            'mass_budget_lb',result.estimated_takeoff_mass_lb,'wing_ft2',r.S_ref, ...
            'span_ft',o.geom.b,'wing_loading_lb_ft2',result.W_TO/r.S_ref, ...
            'vertical_tail_planform_ft2',o.geom.S_vt, ...
            'vertical_tail_dorsal_ft2',o.geom.S_dorsal_vt, ...
            'vertical_tail_total_planform_ft2',o.geom.S_total_vt, ...
            'rudder_planform_ft2',o.geom.S_rudder_vt, ...
            'vertical_tail_height_ft',o.geom.b_vt, ...
            'vertical_tail_root_chord_ft',o.geom.c_root_vt, ...
            'vertical_tail_tip_chord_ft',o.geom.c_tip_vt, ...
            'vertical_tail_sizing_mode',string(o.geom.sizing_mode_vt), ...
            'vertical_tail_area_over_wing',o.geom.S_vt/r.S_ref, ...
            'vertical_tail_volume_coefficient',o.geom.V_vt, ...
            'vertical_tail_arm_ft',o.geom.L_vt, ...
            'directional_control_validated',false, ...
            'aircraft_empty_excluding_crew_lb',a.OEW_breakdown.total, ...
            'crew_lb',360,'passengers_and_baggage_lb',2070, ...
            'motor_peak_total_hp',r.P_motor_peak, ...
            'motor_continuous_total_hp',r.P_motor_continuous, ...
            'turbine_continuous_total_hp',r.P_turbine_continuous, ...
            'battery_nominal_kWh',NaN,'route_nm',c.route_distance_nm, ...
            'cruise_ktas',c.cruise_ktas,'reserve_case',c.reserve_case, ...
            'fuel_burn_per_leg_lb',burn,'loaded_fuel_for_case_lb',fuel, ...
            'fuel_lb_per_available_seat_nm',perSeat, ...
            'average_block_min_including_interleg_turnaround',block, ...
            'wing_fuel_capacity_estimate_lb',tank, ...
            'fuel_volume_screen_pass',c.completed && fuel<=tank, ...
            'span_screen_pass',o.geom.b<cfg.span_limit_ft, ...
            'team_mass_budget_cap_met',result.team_mass_cap_met);
        if result.assessment_feasible, row.battery_nominal_kWh=r.E_battery_nominal_kWh; end
        if isempty(rows), rows=row; else, rows(end+1)=row; end %#ok<AGROW>
    end
end
