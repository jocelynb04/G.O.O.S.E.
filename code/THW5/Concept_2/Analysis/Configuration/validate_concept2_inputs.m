function validate_concept2_inputs(c)
%VALIDATE_CONCEPT2_INPUTS Reject invalid schedules before integration/search.
    positive={'shaft_efficiency','gearbox_hp_each','battery_continuous_C', ...
        'battery_peak_C','battery_charge_C','battery_power_derating', ...
        'battery_energy_derating','battery_specific_energy_Wh_kg', ...
        'charge_storage_efficiency','integration_step_min','capacity_tolerance_kWh', ...
        'capacity_max_kWh','electric_climb_ktas','electric_climb_fpm', ...
        'turbine_climb_ktas','turbine_climb_fpm','descent_ktas','descent_fpm', ...
        'approach_ktas','approach_fpm','restart_delay_s','oei_turbine_climb_fpm', ...
        'cell_nominal_energy_Wh','cell_nominal_voltage','cell_operating_min_voltage', ...
        'cell_max_voltage','span_limit_ft','failure_battery_fraction'};
    for k=1:numel(positive)
        validateattributes(c.(positive{k}),{'numeric'},{'scalar','real','finite','positive'}, ...
            mfilename,positive{k});
    end
    for name={'shaft_efficiency','battery_power_derating','battery_energy_derating', ...
            'charge_storage_efficiency','failure_battery_fraction'}
        assert(c.(name{1})<=1,'validate_concept2_inputs:Fraction','%s must be <=1.',name{1});
    end
    for name={'repeated_legs','cell_series_count','battery_string_count'}
        validateattributes(c.(name{1}),{'numeric'},{'scalar','integer','positive'});
    end
    assert(c.repeated_legs>=2,'validate_concept2_inputs:Cycles','Use at least two repeated legs.');
    assert(c.battery_peak_C>=c.battery_continuous_C, ...
        'validate_concept2_inputs:Rates','Peak discharge must be >= continuous discharge.');
    assert(c.charge_taper_start_soc>=0 && c.charge_taper_start_soc<.9, ...
        'validate_concept2_inputs:Taper','Charge taper must start below the 0.9 SOC ceiling.');
    assert(c.cell_operating_min_voltage<c.cell_nominal_voltage && ...
        c.cell_nominal_voltage<c.cell_max_voltage, ...
        'validate_concept2_inputs:Voltage','Require minimum < nominal < maximum cell voltage.');
    validateattributes(c.wing_loading_sweep_psf,{'numeric'},{'vector','finite','positive','nonempty'});
    validateattributes(c.include_high_speed_mission,{'logical'},{'scalar'});
end
