function r=concept2_geometry_validation(obj,W)
%CONCEPT2_GEOMETRY_VALIDATION Check the imported fixed geometry at trial weight.
    g=obj.geom;
    required=(1+g.excess_buoyancy)*W/g.water_density_fresh_lb_per_ft3;
    available=g.V_enclosed_total;
    r=struct('fixed_openvsp_geometry',~isempty(fieldnames(g.openvsp_reference)), ...
        'float_volume_available_ft3',available,'float_volume_required_ft3',required, ...
        'float_buoyancy_margin_ft3',available-required, ...
        'intact_buoyancy_met',available>=required-1e-8, ...
        'maximum_weight_at_required_buoyancy_lb',available*g.water_density_fresh_lb_per_ft3/(1+g.excess_buoyancy), ...
        'wing_area_ft2',g.S_ref,'wing_span_ft',g.b, ...
        'horizontal_tail_ft2',g.S_ht,'vertical_tail_ft2',g.S_total_vt, ...
        'external_wetted_area_ft2',g.S_wet, ...
        'hydrostatic_stability_verified',false,'directional_control_verified',false);
    if r.fixed_openvsp_geometry
        r.source_file=g.openvsp_reference.source_file;
        r.source_sha256=g.openvsp_reference.source_sha256;
    end
end
