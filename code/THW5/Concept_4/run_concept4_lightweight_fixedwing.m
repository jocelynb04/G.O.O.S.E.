function out = run_concept4_lightweight_fixedwing(Sref_ft2)
if nargin < 1 || isempty(Sref_ft2)
    Sref_ft2 = 325;
end
here = fileparts(mfilename('fullpath'));
J = jsondecode(fileread(fullfile(here,'concept4_aero_hydro_requirements.json')));
A = jsondecode(fileread(fullfile(here,'Concept4_integration_assumptions.json')));

p = SeaplaneProp_Concept4(J);
g = SeaplaneGeom(J,p);
g.S_ref = Sref_ft2;
a = SeaplaneAero_Concept4(J,g);
w = SeaplaneWeights(J,g,p);
m = Concept4Mission(J,g,a,p,A);

span_limit = J.rfp_performance_requirements.maximum_wingspan_ft_strictly_below;
span_design = span_limit - c4_get(A,'span_design_margin_ft',1);
if g.b > span_design || g.b >= span_limit
    error('C4:Span','Wing span exceeds chosen design margin or RFP limit.');
end

W = J.sizing.W_TO_guess_lbf;
W_limit = c4_get(J.sizing,'optional_team_MTOW_target_lbf',12500);
relaxation = J.sizing.relaxation;
max_iter = J.sizing.max_iter;
tol_lb = 0.05;
power_margin_fraction = 0.10;
installation = J.weights.propulsion_integration;
installation_factor = 1 + installation.wiring_fraction_of_prop_mass ...
    + installation.heat_sink_thermal_fraction_of_prop_mass ...
    + installation.cowl_nacelle_fraction_of_prop_mass ...
    + installation.struts_mounting_fraction_of_prop_mass ...
    + installation.spinner_fraction_of_prop_mass;

history = nan(max_iter,8);
converged = false;
for k = 1:max_iter
    r = calculate_pass(W);
    history(k,:) = [k,W,r.gross_lb,r.motor_hp,r.generator_hp, ...
        r.battery_capacity_kwh,r.battery_mass_lb,r.fuel_lb];
    if abs(r.gross_lb-W) < tol_lb
        converged = true;
        W = r.gross_lb;
        break;
    end
    W = W+relaxation*(r.gross_lb-W);
end

r = calculate_pass(W);
residual_lb = W-r.gross_lb;
if ~converged || abs(residual_lb) > 0.2
    status = 'NOT_CONVERGED';
elseif r.gross_lb > W_limit
    status = 'CONVERGED_BUT_OVER_TEAM_WEIGHT_LIMIT';
else
    status = 'PRELIMINARY_WEIGHT_CLOSED_UNVERIFIED_WATER_TAKEOFF';
end

history = history(1:k,:);
H = array2table(history,'VariableNames', ...
    {'Iteration','InputWeight_lb','CalculatedWeight_lb','MotorRating_hp', ...
    'GeneratorEngine_hp','BatteryCapacity_kWh','BatteryMass_lb','MissionFuel_lb'});
out = struct('status',status,'converged',converged, ...
    'wing_area_ft2',Sref_ft2,'wing_span_ft',g.b, ...
    'weight_lb',r.gross_lb,'team_weight_limit_lb',W_limit, ...
    'weight_margin_lb',W_limit-r.gross_lb,'mass_closure_residual_lb',residual_lb, ...
    'motor_shaft_rating_hp',r.motor_hp, ...
    'generator_engine_rating_hp',r.generator_hp, ...
    'battery_capacity_kwh',r.battery_capacity_kwh, ...
    'battery_mass_lb',r.battery_mass_lb, ...
    'battery_bus_power_capability_kw',r.battery_capability_kw, ...
    'peak_mission_battery_bus_kw',r.peak_mission_battery_kw, ...
    'mission_fuel_lb',r.fuel_lb,'estimated_OEW_lb',r.OEW_lb, ...
    'payload_lb',r.payload_lb,'mission_final_SOC',r.final_SOC, ...
    'required_climb2000_hp',r.climb2000_hp, ...
    'required_climb500_hp',r.climb500_hp, ...
    'required_cruise180_hp',r.cruise180_hp, ...
    'iterations',k,'history',H, ...
    'limitations',{{'Unverified water takeoff power and distance', ...
    'Unverified motor-out drag and yaw', ...
    'Unverified pack-specific energy and power', ...
    'Unverified float mass and aerodynamic component inputs', ...
    'Single fixed wing area, not a global minimum-weight design'}});

output_dir = fullfile(here,'results',sprintf('fixedwing_%g',Sref_ft2));
if ~isfolder(output_dir)
    mkdir(output_dir);
end
writetable(H,fullfile(output_dir,'iteration_history.csv'));
summary = rmfield(out,{'history'});
write_json_C4(fullfile(output_dir,'summary.json'),summary);

fprintf('\n%s\n',status);
fprintf('Wing area: %.2f ft^2 | Span: %.2f ft\n',Sref_ft2,g.b);
fprintf('Calculated TOGW: %.2f lb | Limit: %.2f lb | Margin: %.2f lb\n', ...
    r.gross_lb,W_limit,W_limit-r.gross_lb);
fprintf('Mass closure residual: %.4f lb | Iterations: %d\n',residual_lb,k);
fprintf('Motor: %.2f shp | Generator engine: %.2f shp\n',r.motor_hp,r.generator_hp);
fprintf('Battery: %.2f kWh | %.2f lb | Bus limit by mass: %.2f kW\n', ...
    r.battery_capacity_kwh,r.battery_mass_lb,r.battery_capability_kw);
fprintf('Mission peak battery: %.2f kW | Final SOC: %.4f\n', ...
    r.peak_mission_battery_kw,r.final_SOC);
fprintf('OEW: %.2f lb | Payload: %.2f lb | Fuel: %.2f lb\n', ...
    r.OEW_lb,r.payload_lb,r.fuel_lb);
fprintf('Results: %s\n',output_dir);

    function rr = calculate_pass(Wguess)
        % A new sizing trial has no selected installed pack until mass closure.
        p.battery_installed_mass_kg = [];
       
    W_power = max(Wguess,W_limit);

    c0 = c4_required_climb_hp(W_power,Sref_ft2,0,2000,a,p.eta_p_climb,35);
    c10 = c4_required_climb_hp(W_power,Sref_ft2,10000,500,a,p.eta_p_climb,35);
    cc = constraint_cruise_speed_C4(W_power,Sref_ft2,10000,180,a,p.eta_p_cruise);
        if isempty(c0) || isempty(c10) || isempty(cc)
            error('C4:Constraint','No valid climb/cruise solution at this weight and wing area.');
        end
        p.P_SL = max([c0.hp,c10.hp,cc.hp])/p.motor_continuous_fraction ...
            *(1+c4_get(A,'motor_power_margin_fraction',0.01));
        p.engine_shaft_power_sl_hp_each = 1;
        gen0 = p.generator_available_bus_kw(0);
        gen10 = p.generator_available_bus_kw(10000);
        phi = J.propulsion.phi.climb;
        p.engine_shaft_power_sl_hp_each = max([ ...
            p.motor_bus_kw(cc.hp)/gen10, ...
            (1-phi)*p.motor_bus_kw(c0.hp)/gen0, ...
            (1-phi)*p.motor_bus_kw(c10.hp)/gen10]) ...
            *(1+A.generator_power_margin_fraction);

        probe = m.run(Wguess,'std_mission',true);
        usable_soc = p.battery_initial_soc-p.battery_min_soc;
        p.battery_capacity_kwh = max(A.minimum_battery_capacity_kwh, ...
            (probe.peak_cumulative_pack_deficit_kwh/usable_soc) ...
            *(1+A.battery_energy_margin_fraction));
        flight = m.run(Wguess,'std_mission',false);
        bd = w.OEW_breakdown(Wguess);
        energy_mass_kg = p.battery_capacity_kwh ...
            /J.propulsion.battery_specific_energy_kwh_per_kg;
        power_mass_kg = flight.peak_battery_discharge_bus_kw ...
            *(1+power_margin_fraction) ...
            /(p.eta_battery_discharge*J.propulsion.battery_specific_power_kw_per_kg);
        batt_mass_lb = max(energy_mass_kg,power_mass_kg)*2.20462262185;
        batt_available_kw = batt_mass_lb/2.20462262185 ...
            *J.propulsion.battery_specific_power_kw_per_kg*p.eta_battery_discharge;
        % Bind the mass selected above; recheck the full mission with its
        % installed power limit. Do not inherit a previous iteration's pack.
        p.battery_installed_mass_kg = batt_mass_lb/2.20462262185;
        flight = m.run(Wguess,'std_mission',false);
        if flight.peak_battery_discharge_bus_kw > p.battery_discharge_limit_bus_kw()+1e-6
            error('C4:Battery','Required mission battery power exceeds mass-based capability.');
        end
        adjusted_OEW = bd.total - (bd.prop_battery-batt_mass_lb)*installation_factor;
        rr = struct('gross_lb',adjusted_OEW+w.payload()+flight.total_fuel_lb, ...
            'OEW_lb',adjusted_OEW,'payload_lb',w.payload(), ...
            'fuel_lb',flight.total_fuel_lb,'final_SOC',flight.soc_end, ...
            'motor_hp',p.P_SL,'generator_hp',p.engine_shaft_power_sl_hp_each, ...
            'battery_capacity_kwh',p.battery_capacity_kwh, ...
            'battery_mass_lb',batt_mass_lb, ...
            'battery_capability_kw',batt_available_kw, ...
            'peak_mission_battery_kw',flight.peak_battery_discharge_bus_kw, ...
            'climb2000_hp',c0.hp,'climb500_hp',c10.hp,'cruise180_hp',cc.hp);
    end
end
