function study = run_concept1_weight_reduction_trade()
%RUN_CONCEPT1_WEIGHT_REDUCTION_TRADE Screen pack and airframe drag targets.
% Pack energy density, discharge rate, and retention are joint assumptions.
% Drag reductions are sensitivity inputs for Cfe and need geometry evidence.
here = fileparts(mfilename('fullpath'));
setup_jason_edits();
cfg = jsondecode(fileread(concept1_requirements_path()));
W0 = 12490;
wingAR = 64.9^2*18.3/W0;
installAllowance = 130; % both nacelles, from the motor-generator planning case
settings = [250,6,1,1; 300,6,1,1; 250,8,1,1; 300,8,1,1; ...
    300,8,1,0.95; 300,8,1,0.90; 300,8,0.8,0.90; 300,8,0.8,0.85];
study = table();
for k = 1:size(settings,1)
    whkg = settings(k,1);
    dischargeC = settings(k,2);
    retention = settings(k,3);
    dragFactor = settings(k,4);
    [~,mission,early] = run_concept1_energy_trade(DesignWeight=W0, ...
        AspectRatio=wingAR,LandingCLmax=2.6,CombustionRating=1500, ...
        EngineDryWeight=340,EngineBSFC=0.595*783/750, ...
        AssistDelaySeconds=0,WriteResults=false,PackWhPerKg=whkg, ...
        DischargeC=dischargeC,CapacityRetention=retention,SkinFrictionFactor=dragFactor);
    bareMotor = mission.MotorRated_shp*0.745699872/ ...
        cfg.propulsion.motor_specific_power_kW_kg*2.20462262;
    previousAllowance = bareMotor*(cfg.weights.concept1.motor_installation_factor-1);
    gross = mission.WeightBuildup_lbf+installAllowance-previousAllowance;
    designGap = gross-W0;
    capGap = gross-cfg.aircraft_requirements.maximum_certificated_takeoff_weight_exclusive_lbf;
    row = table(whkg,dischargeC,100*retention,100*(1-dragFactor), ...
        mission.Pack_kWh,mission.NameplatePack_kWh,mission.Battery_lbf, ...
        mission.MissionFuel_lbf,early.SOCafterBalk_percent,gross,designGap,capGap, ...
        early.MotorWithinRating && early.BatteryWithinPowerLimit && early.SOCAboveMinimum, ...
        'VariableNames',{'Pack_Wh_kg','Discharge_C','RetainedCapacity_percent', ...
        'CfeReduction_percent','EffectivePack_kWh','NameplatePack_kWh','Battery_lbf', ...
        'MissionFuel_lbf','EarlyReturnSOC_percent','InstalledGross_lbf', ...
        'OverDesignWeight_lbf','OverMTOWCeiling_lbf','EarlyReturnPass'});
    study = [study;row];
end
disp(study);
writetable(study,fullfile(here,'results','RFP_weight_reduction_trade.csv'));
end
